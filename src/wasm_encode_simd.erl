-module(wasm_encode_simd).
-moduledoc """
The `0xFD` opcode space, fixed-width SIMD, written back to bytes:
`wasm_decode_simd` run backwards. Add a vector instruction here when you add
it there.

The clauses are in the decoder's order, one per sub-opcode, with the prefix
and the sub-opcode as literal bytes: the relaxed instructions above 255 take
two bytes of LEB128. The immediate shapes are the decoder's five: none, a
memory argument, a memory argument and a lane, a lane, sixteen raw bytes.
""".

-export([instr/1]).

-doc """
One `0xFD` instruction, or `false` when the instruction is not in this space,
so `wasm_encode_code` can try the next one.
""".
